let currentLanguage = "fa";
const header = document.getElementById("siteHeader");
const menuToggle = document.getElementById("menuToggle");
const navLinks = document.getElementById("navLinks");

function t(key) {
  return translations[currentLanguage][key] || key;
}

function setLanguage(language) {
  currentLanguage = language;
  const dictionary = translations[language];
  document.documentElement.lang = language;
  document.documentElement.dir = language === "fa" ? "rtl" : "ltr";
  document.body.classList.toggle("fa", language === "fa");
  document.body.classList.toggle("en", language === "en");
  document.title = dictionary.pageTitle;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (dictionary[key]) element.textContent = dictionary[key];
  });
  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const key = element.dataset.i18nAlt;
    if (dictionary[key]) element.alt = dictionary[key];
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const key = element.dataset.i18nPlaceholder;
    if (dictionary[key]) element.placeholder = dictionary[key];
  });

  const languageButton = document.getElementById("languageBtn");
  if (languageButton) languageButton.textContent = language === "fa" ? "English" : "فارسی";
  document.querySelectorAll(".form-status[data-default-status]").forEach((element) => {
    element.textContent = dictionary.formNotice;
  });
}

function closeMenu() {
  if (!menuToggle || !navLinks) return;
  menuToggle.setAttribute("aria-expanded", "false");
  menuToggle.setAttribute("aria-label", currentLanguage === "fa" ? "باز کردن منو" : "Open menu");
  navLinks.classList.remove("is-open");
  header.classList.remove("is-menu-open");
}

if (menuToggle && navLinks) {
  menuToggle.addEventListener("click", () => {
    const isOpen = menuToggle.getAttribute("aria-expanded") === "true";
    menuToggle.setAttribute("aria-expanded", String(!isOpen));
    menuToggle.setAttribute("aria-label", isOpen ? (currentLanguage === "fa" ? "باز کردن منو" : "Open menu") : (currentLanguage === "fa" ? "بستن منو" : "Close menu"));
    navLinks.classList.toggle("is-open", !isOpen);
    header.classList.toggle("is-menu-open", !isOpen);
  });
  navLinks.querySelectorAll("a").forEach((link) => link.addEventListener("click", closeMenu));
  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape") closeMenu();
  });
}

const languageButton = document.getElementById("languageBtn");
if (languageButton) {
  languageButton.addEventListener("click", () => setLanguage(currentLanguage === "fa" ? "en" : "fa"));
}

// Curtain-style top bar: hide while scrolling down, reveal while scrolling up.
let previousScrollY = window.scrollY;
let scrollScheduled = false;
window.addEventListener("scroll", () => {
  if (scrollScheduled) return;
  scrollScheduled = true;
  window.requestAnimationFrame(() => {
    const currentY = window.scrollY;
    const menuOpen = header && header.classList.contains("is-menu-open");
    if (header && !menuOpen) {
      if (currentY < 50 || currentY < previousScrollY - 6) {
        header.classList.remove("is-hidden");
      } else if (currentY > previousScrollY + 8 && currentY > 140) {
        header.classList.add("is-hidden");
      }
    }
    previousScrollY = currentY;
    scrollScheduled = false;
  });
}, { passive: true });

// Reveal cards gently when they enter the viewport.
const revealItems = document.querySelectorAll(".reveal");
if ("IntersectionObserver" in window) {
  const observer = new IntersectionObserver((entries, activeObserver) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible");
        activeObserver.unobserve(entry.target);
      }
    });
  }, { threshold: 0.12 });
  revealItems.forEach((item) => observer.observe(item));
} else {
  revealItems.forEach((item) => item.classList.add("is-visible"));
}

function readForm(form) {
  const data = new FormData(form);
  return {
    name: String(data.get("name") || "").trim(),
    email: String(data.get("email") || "").trim(),
    subject: String(data.get("subject") || "").trim(),
    message: String(data.get("message") || "").trim()
  };
}

function validateForm(form, values, statusElement) {
  if (!form.reportValidity()) {
    if (statusElement) statusElement.textContent = t("invalidForm");
    return false;
  }
  return Boolean(values.name && values.email && values.subject && values.message);
}

function buildMessage(values, kind) {
  const intro = kind === "support"
    ? (currentLanguage === "fa" ? "درخواست پشتیبانی جدید از وب‌سایت:" : "New support request from the website:")
    : t("contactMessageIntro");
  const labels = currentLanguage === "fa"
    ? ["نام", "ایمیل", "موضوع", "پیام"]
    : ["Name", "Email", "Subject", "Message"];
  return [intro, "", labels[0] + ": " + values.name, labels[1] + ": " + values.email, labels[2] + ": " + values.subject, labels[3] + ": " + values.message].join("\n");
}

function openWhatsApp(form, kind, statusElement) {
  const values = readForm(form);
  if (!validateForm(form, values, statusElement)) return;
  const message = buildMessage(values, kind);
  const phone = "989050043902";
  const url = "https://wa.me/" + phone + "?text=" + encodeURIComponent(message);
  if (statusElement) statusElement.textContent = t("whatsappReady");
  window.location.assign(url);
}

function openEmail(form, kind, statusElement) {
  const values = readForm(form);
  if (!validateForm(form, values, statusElement)) return;
  const subjectPrefix = kind === "support" ? (currentLanguage === "fa" ? "درخواست پشتیبانی: " : "Support request: ") : "";
  const body = buildMessage(values, kind);
  const url = "mailto:mehrzada9999@gmail.com?subject=" + encodeURIComponent(subjectPrefix + values.subject) + "&body=" + encodeURIComponent(body);
  if (statusElement) statusElement.textContent = t("emailReady");
  window.location.href = url;
}

const contactForm = document.getElementById("contactForm");
if (contactForm) {
  const status = document.getElementById("contactStatus");
  contactForm.addEventListener("submit", (event) => {
    event.preventDefault();
    openWhatsApp(contactForm, "contact", status);
  });
}
const supportForm = document.getElementById("supportForm");
if (supportForm) {
  const status = document.getElementById("supportStatus");
  supportForm.addEventListener("submit", (event) => {
    event.preventDefault();
    openWhatsApp(supportForm, "support", status);
  });
}
document.querySelectorAll("[data-email-form]").forEach((button) => {
  button.addEventListener("click", () => {
    const form = document.getElementById(button.dataset.emailForm);
    const status = document.getElementById(button.dataset.emailForm === "supportForm" ? "supportStatus" : "contactStatus");
    const kind = button.dataset.emailForm === "supportForm" ? "support" : "contact";
    if (form) openEmail(form, kind, status);
  });
});

